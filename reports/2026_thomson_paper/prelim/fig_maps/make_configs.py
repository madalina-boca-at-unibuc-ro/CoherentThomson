#!/usr/bin/env python3
"""Generate the Sec. IV.C field-map configs: a0 = 1, N_c = 8, LG (0, 2), N = 1 and 2, 10 um and its 800 nm scaled twin.

Each config is the matching fig_spectrum config (../fig_spectrum/configs/<id>.cfg, itself generated: same laser, beam,
pulse, formula, trajectory_NT) with only the screen and the frequency changed:
  - frequency: one omega_list entry, N:omega_peak, the largest maximum of that run's screen-integrated photon spectrum
    (peak_frequencies.py, parabolic refinement of the 0.002 grid); each twin uses its own peak;
  - screen: circular, at the same Z/Z_* = 2.85, out to THETA_MAX theta_* (at the peak, 4e-6 of the flux is beyond
    16 theta_*, 5e-4 beyond 12), equal-area radial grid with N_R rings (first ring off axis at
    THETA_MAX / sqrt(N_R - 1) theta_*), N_PHI azimuths (N_PHI - 1 distinct: the grid repeats phi = 0 at 2 pi);
    plot_observables takes d/dphi by FFT, so N_PHI - 1 must exceed 2 |J| + 1 (J = -3, -6 for N = 1, 2);
  - lattice spacing from the aliasing rule theta_rep / theta_* = pi w0 / ((omega/omega_1) d) >= 1.5 THETA_MAX
    (coarser than the spectrum runs, whose lines went to 24 theta_*).

Don't edit the configs by hand: change this script and regenerate.
Usage: python3 make_configs.py   (writes configs/<id>.cfg and prints a summary)
"""
import math
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SPECTRUM_CONFIGS = os.path.join(HERE, '..', 'fig_spectrum', 'configs')
OUT = os.path.join(HERE, 'configs')
OUTPUT_ROOT = 'output/paper_2026/prelim/fig_maps'

W0_OVER_LAMBDA = 10.0
THETA_MAX = 16.0            # screen radius in theta_*
N_R = 1024
N_PHI = 65
REPLICA_MARGIN = 1.5
# run id -> (harmonic N, omega_peak in omega/omega_1), from peak_frequencies.py (2026-11-26)
RUNS = {
    '10um_a0_1p0_Nc8_N1': (1, 1.2683),
    '800nm_a0_1p0_Nc8_N1': (1, 1.2682),
    '10um_a0_1p0_Nc8_N2': (2, 2.5401),
    '800nm_a0_1p0_Nc8_N2': (2, 2.5385),
}
# lattice spacing (lambda) per harmonic: the largest value in {1, 0.5, 0.25} meeting the replica margin
SPACINGS = (1.0, 0.5, 0.25)


def get_value(lines, key):
    for line in lines:
        m = re.match(rf'^\s*{re.escape(key)}\s+(\S+)', line)
        if m:
            return m.group(1)
    raise KeyError(key)


def set_key(lines, key, value):
    pattern = re.compile(rf'^(\s*){re.escape(key)}(\s+)(\S+(?:\s+[A-Za-z_]\w*)?)(\s*(#.*)?)$')
    for i, line in enumerate(lines):
        m = pattern.match(line.rstrip('\n'))
        if m:
            comment = f'  {m.group(5)}' if m.group(5) else ''
            lines[i] = f'{key:<23} {value}{comment}\n'
            return
    lines.append(f'{key:<23} {value}\n')   # optional keys (omega_list) are absent from the base


def main():
    os.makedirs(OUT, exist_ok=True)
    print(f'{"id":<24}{"N":>3}{"omega":>9}{"Z [w0]":>10}{"R [w0]":>9}{"d [lambda]":>12}{"margin":>8}'
          f'{"ring 1 [theta_*]":>18}')
    for run_id, (N, omega) in RUNS.items():
        with open(os.path.join(SPECTRUM_CONFIGS, f'{run_id}.cfg')) as f:
            lines = [ln for ln in f.readlines() if not ln.startswith('# GENERATED') and not ln.startswith(f'# {run_id}')
                     and not ln.startswith('# D = ')]
        Z = float(get_value(lines, 'rectangular_detector_distance'))      # in w0, Z/Z_* = 2.85
        z_over_zs = 2.85
        R = THETA_MAX * z_over_zs                                         # theta_* Z_* = w0
        d = next(s for s in SPACINGS if math.pi * W0_OVER_LAMBDA / (omega * s) >= REPLICA_MARGIN * THETA_MAX)
        margin = math.pi * W0_OVER_LAMBDA / (omega * d) / THETA_MAX
        values = {
            'output_folder': f'{OUTPUT_ROOT}/{run_id}',
            'dense_frequency_spectrum': 'false',
            'omega_list': f'{N}:{omega} first_harmonic_frequency',
            'detector_type': 'circular',
            'circular_detector_R_min': '0.0 lambda',
            'circular_detector_R_max': f'{R:.3f} w0',
            'circular_detector_N_R': str(N_R),
            'circular_detector_N_phi': str(N_PHI),
            'circular_detector_distance': f'{Z:.1f} w0',
            'beam_lattice_spacing': f'{d} lambda',
        }
        for key, value in values.items():
            set_key(lines, key, value)
        header = (f'# GENERATED by reports/2026_thomson_paper/prelim/fig_maps/make_configs.py: do not edit.\n'
                  f'# {run_id}: Sec. IV.C field maps. Base: fig_spectrum/configs/{run_id}.cfg; omega_list {N}:{omega}'
                  f' (spectrum peak); circular screen Z/Z_* = {z_over_zs}, R = {THETA_MAX:g} theta_*,'
                  f' {N_R} x {N_PHI}; d = {d} lambda.\n')
        with open(os.path.join(OUT, f'{run_id}.cfg'), 'w') as f:
            f.write(header + ''.join(lines))
        print(f'{run_id:<24}{N:>3}{omega:>9}{Z:>10.1f}{R:>9.2f}{d:>12}{margin:>8.2f}'
              f'{THETA_MAX / math.sqrt(N_R - 1):>18.2f}')


if __name__ == '__main__':
    main()
